"""Regenerate core/ethics_core_manifest.py from core/ethics_core/.

HUMAN DEVELOPER STEP ONLY. Run after an intentional change to the ethics
core data, then commit the data change and the regenerated manifest together
in one PR so the digest change is visible in review:

    python scripts/rebuild_ethics_manifest.py

The robot runtime never imports or runs this script (it is not part of the
installed package), and it uses no signing key.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE_DIR = ROOT / "core" / "ethics_core"
OUT = ROOT / "core" / "ethics_core_manifest.py"

HEADER = '''"""Pinned sha256 manifest for core/ethics_core/.

GENERATED by ``python scripts/rebuild_ethics_manifest.py`` (a human
developer step, reviewed via PR). Do not edit by hand; the robot runtime
never regenerates this file.
"""

from types import MappingProxyType

PINNED_MANIFEST = MappingProxyType(
    {
'''


def main() -> int:
    entries = sorted(CORE_DIR.iterdir())
    bad = [p.name for p in entries if p.is_symlink() or not p.is_file()]
    if bad:
        print(f"refusing: non-regular entries in {CORE_DIR}: {bad}", file=sys.stderr)
        return 1
    parts = [HEADER]
    for p in entries:
        digest = hashlib.sha256(p.read_bytes()).hexdigest()
        parts.append(f'        "{p.name}":\n            "{digest}",\n')
        print(f"{digest}  {p.name}")
    parts.append("    }\n)\n")
    OUT.write_text("".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
